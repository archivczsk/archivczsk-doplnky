# -*- coding: utf-8 -*-

from Plugins.Extensions.archivCZSK.archivczsk import ArchivCZSK
import base64
from .template import HTTPRequestHandlerTemplate
from time import time
import subprocess
import select
import os

# #################################################################################################

class PlayliveTVHTTPRequestHandler(HTTPRequestHandlerTemplate):
	'''
	Http request handler that implements playlive handler that extracts channel key generated by bouquet generator
	and redirects to real stream url
	'''
	def __init__(self, content_provider, addon, cache_life=900):
		super(PlayliveTVHTTPRequestHandler, self).__init__(content_provider, addon)
		self.live_cache = {}
		self.cache_life = cache_life
		self.tsconvert_cmd_path = [
			os.path.join(addon.get_info('data_path'), 'tsconvert_cmd.txt'),
			os.path.join(ArchivCZSK.get_addon('tools.archivczsk').get_info('data_path'), 'tsconvert_cmd.txt')
		]

	# #################################################################################################

	def live_cache_cleanup(self):
		act_time = int(time())

		to_clean_list = []
		for k, v in self.live_cache.items():
			if v['life'] < act_time:
				to_clean_list.append(k)

		for k in to_clean_list:
			del self.live_cache[k]

	# #################################################################################################

	def live_cache_get(self, channel_key):
		if self.cache_life > 0:
			cache_result = self.live_cache.get(channel_key)
			if cache_result and cache_result.get('life', 0) > int(time()):
				cache_result['life'] = int(time()) + self.cache_life
				return cache_result['result']

		return None

	# #################################################################################################

	def live_cache_put(self, channel_key, result):
		if self.cache_life > 0:
			self.live_cache[channel_key] = {
				'life': int(time()) + self.cache_life,
				'result': result
			}
			self.live_cache_cleanup()

	# #################################################################################################

	def decode_channel_key(self, path):
		if path.endswith('.m3u8'):
			path = path[:-5]

		if path.endswith('.mpd'):
			path = path[:-4]

		return base64.b64decode(path.encode('utf-8')).decode("utf-8")

	# #################################################################################################

	def get_url_by_channel_key(self, channel_key):
		'''
		This is default implementation, that just forwards this call to content provider.
		Replace it with your own implementation if you need something different.
		'''
		return self.cp.get_url_by_channel_key(channel_key)

	# #################################################################################################

	def P_playlive(self, request, path):
		channel_key = self.decode_channel_key(path)

		result = self.live_cache_get(channel_key)
		if not result:
			result = self.get_url_by_channel_key(channel_key)

			if not result:
				return self.reply_error404(request)

			self.live_cache_put(channel_key, result)

		return self.reply_redirect(request, result)

	# #################################################################################################

	def P_playlivets(self, request, path):
		return self.convert_stream_to_ts(request, self.cp.http_endpoint + '/playlive/' + path)

	# #################################################################################################

	def convert_stream_to_ts(self, request, input_url):
		cmd = None
		for path in self.tsconvert_cmd_path:
			if os.path.isfile(path):
				with open(path, 'r') as f:
					cmd = f.read().strip().format(input_url=input_url).split(' ')
				break
		else:
			cmd = '-nostdin -loglevel info -i {input_url} -map 0 -c:v copy -c:a copy -c:s copy -muxdelay 0 -muxpreload 0 -mpegts_flags +resend_headers -f mpegts pipe:1'.format(input_url=input_url)
			cmd = [None] + cmd.split(' ')

		return self.ffmpeg_stream_ts(request, cmd)


